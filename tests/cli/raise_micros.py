"""raise_micros: `cone_check` then `raise` end to end on small netlist micros, through odin3.

Usage: raise_micros.py ODIN3 EQUIV_CHECK OUT_DIR

Each micro is a BLIF text (generated by cone_check_micros) read with `read_blif`, written as the
reference BLIF and as JSON (`write_json --odin3`), marked in the JSON as cone_check_micros does,
read back and run through `cone_check` and `raise`; the result is lowered, written as BLIF and
compared with the reference by equiv-check (Phase 7 spec 3.4 R-4: the raised design is equivalent
to the input).  A swapped binding (cone_check says `differs`) and a design never proved are
refused by raise with the design unchanged.  Exit 0 when every micro gives its expected result,
1 otherwise, 2 on a usage error.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import cone_check_micros as cc


def raised(binary: str, equiv: str, work: Path, micro: cc.Micro) -> str:
    """'' when raise replaces the cone and the result is equivalent to the input."""
    blif, ref, plain, marked, out = (work / n for n in ("t.blif", "ref.blif", "a.json", "b.json",
                                                        "out.blif"))
    blif.write_text(micro.blif, encoding="utf-8")
    first = cc.odin3(binary, f"read_techlib {cc.TECHLIB}; read_blif {blif}; write_blif {ref}; "
                             f"write_json --odin3 {plain}")
    if first.returncode != 0:
        return "could not read the micro: " + first.stderr.strip()[-200:]
    cc.mark(plain, marked, micro)
    args = " ".join([f"-attr grp={cc.GROUP}", f"-cell {micro.cell}", *micro.params])
    script = (f"read_techlib {cc.TECHLIB}; read_json --top m {marked}; cone_check {args}; "
              f"raise {args}; lower; abc --lut 4; write_blif {out}")
    second = cc.odin3(binary, script)
    text = second.stderr + second.stdout
    if micro.expect == "refused":
        ok = second.returncode != 0 and micro.refusal in text
        return "" if ok else "expected a refusal: " + text.strip()[-200:]
    if second.returncode != 0 or "nodes replaced by one" not in text:
        return "cone_check or raise failed: " + text.strip()[-300:]
    verdict = subprocess.run([equiv, str(ref), str(out)], capture_output=True, text=True,
                             check=False)
    if verdict.returncode != 0:
        return f"equiv-check exit {verdict.returncode}: " + (verdict.stdout + verdict.stderr).strip()[-200:]
    return ""


def micros() -> list[cc.Micro]:
    out: list[cc.Micro] = []
    for width in (4, 8):
        text, binding = cc.ripple(width)
        params = [f"-param {p}_WIDTH={width}" for p in ("A", "B", "Y")]
        out.append(cc.Micro(f"ripple{width}_raised", text, binding, "$add", "equivalent",
                            params=params))
    text, binding = cc.and_bits(3)
    out.append(cc.Micro("and3_raised", text, binding, "$and", "equivalent",
                        params=[f"-param {p}_WIDTH=3" for p in ("A", "B", "Y")]))
    text, binding = cc.ripple(4)
    swapped = dict(binding)
    swapped["a0"], swapped["a1"] = binding["a1"], binding["a0"]
    add4 = [f"-param {p}_WIDTH=4" for p in ("A", "B", "Y")]
    out.append(cc.Micro("ripple4_swapped_refused", text, swapped, "$add", "refused",
                        refusal="not equivalent", params=add4))
    return out


def never_proved(binary: str, work: Path) -> str:
    """raise on a marked design that cone_check never saw is refused."""
    micro = micros()[0]
    blif, plain, marked = (work / n for n in ("t.blif", "a.json", "b.json"))
    blif.write_text(micro.blif, encoding="utf-8")
    first = cc.odin3(binary, f"read_techlib {cc.TECHLIB}; read_blif {blif}; write_json --odin3 "
                             f"{plain}")
    if first.returncode != 0:
        return "could not read the micro: " + first.stderr.strip()[-200:]
    cc.mark(plain, marked, micro)
    args = " ".join([f"-attr grp={cc.GROUP}", f"-cell {micro.cell}", *micro.params])
    second = cc.odin3(binary, f"read_techlib {cc.TECHLIB}; read_json --top m {marked}; "
                              f"raise {args}")
    text = second.stderr + second.stdout
    ok = second.returncode != 0 and "no cone_check result" in text
    return "" if ok else "expected a refusal: " + text.strip()[-200:]


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    binary, equiv, out_dir = argv[1], argv[2], Path(argv[3])
    failed = 0
    cases = micros()
    for micro in cases:
        work = out_dir / micro.name
        work.mkdir(parents=True, exist_ok=True)
        reason = raised(binary, equiv, work, micro)
        failed += 1 if reason else 0
        print(f"{micro.name} {micro.expect if not reason else 'FAIL: ' + reason}", flush=True)
    work = out_dir / "never_proved"
    work.mkdir(parents=True, exist_ok=True)
    reason = never_proved(binary, work)
    failed += 1 if reason else 0
    print(f"never_proved_refused {'ok' if not reason else 'FAIL: ' + reason}", flush=True)
    print(f"raise_micros: {len(cases) + 1} micros, {failed} failed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
