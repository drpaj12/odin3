#!/usr/bin/env bash
# gen.sh: regenerate the committed netlist fixtures of Phase 6.1 (spec G-5 to G-7) with Yosys 0.55.
# Run from anywhere; needs $VTR_ROOT/build/bin/yosys (Yosys 0.55, docs/ORACLES.md). For each micro:
#   <micro>/rtl.v         copy of the RTL (tests/micro/verilog/..., or hand-written)
#   <micro>/mapped.v      cmos.v cells, no attributes (the reverse-engineering case: no `src`)
#   <micro>/mapped_src.v  the same netlist with Yosys `src` attributes
#   <micro>/mapped.blif   the same netlist as BLIF (Yosys `.subckt` form, spec G-5)
# Flow: synth -flatten; dfflegalize to $_DFF_P_ and $_DFFSR_PPP_ only; abc -g NAND,NOR;
# opt_clean, insbuf (a $_BUF_ for each wire-to-wire connection); techmap -map cells/cmos_map.v; check -assert (fails on any other cell type).
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/../.." && pwd)"
yosys="${YOSYS:-${VTR_ROOT:-$HOME/odin3-ws/external/vtr-verilog-to-routing}/build/bin/yosys}"
if ! "$yosys" -V | grep -q '^Yosys 0\.55 '; then
    echo "gen.sh: $yosys is not Yosys 0.55" >&2
    exit 2
fi
cd "$here"
# micro name, RTL source under tests/micro/verilog (or - for a hand-written rtl.v)
micros=(
    "dffsr common/dffsr.v" "dff common/dff.v" "dffe common/dffe.v" "adff common/adff.v"
    "mux common/mux.v" "adder common/adder.v"
    "bm_DL_Dff_w_synch_reset micro/bm_DL_Dff_w_synch_reset.v" "regen -" "cone -"
)
for entry in "${micros[@]}"; do
    read -r name src <<<"$entry"
    mkdir -p "$name"
    if [ "$src" != "-" ]; then
        cp "$root/tests/micro/verilog/$src" "$name/rtl.v"
        chmod 644 "$name/rtl.v"
        if [ "$name" = adder ]; then
            # common/adder.v instantiates add_add_module but defines add_module (it cannot be read
            # as it stands); the fixture copy instantiates the module the file defines.
            sed -i 's/add_add_module/add_module/' "$name/rtl.v"
        fi
    fi
    (
        cd "$name"
        top="$(sed -n 's/^[[:space:]]*module[[:space:]]\+\([A-Za-z0-9_]*\).*/\1/p' rtl.v | head -n 1)"
        for form in plain src; do
            out=mapped.v
            attr=-noattr
            if [ "$form" = src ]; then
                out=mapped_src.v
                attr=
            fi
            "$yosys" -q -p "
                read_verilog -lib ../cells/cmos.v
                read_verilog rtl.v
                synth -flatten -top $top
                dfflegalize -cell \$_DFF_P_ x -cell \$_DFFSR_PPP_ x
                abc -g NAND,NOR
                delete t:\$scopeinfo
                opt_clean
                insbuf -buf \$_BUF_ A Y
                write_blif -icells mapped.blif.tmp
                techmap -map ../cells/cmos_map.v
                check -assert
                write_verilog $attr $out" >/dev/null
        done
        # The mapped.blif is the same netlist before techmap; $_DFFSR_PPP_ gets its model.
        grep -v '^# Generated by' mapped.blif.tmp >mapped.blif
        rm mapped.blif.tmp
        if grep -q 'subckt \$_DFFSR_PPP_' mapped.blif; then
            sed '/^#/d' ../cells/dffsr_sync.blif >>mapped.blif
        fi
        sed -i '1{/^\/\* Generated by/d}' mapped.v mapped_src.v
    )
    echo "gen.sh: $name"
done
