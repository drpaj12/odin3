class LibertyTest(unittest.TestCase):
    def test_golden_text(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            lib, out = Path(tmp) / "x.lib", Path(tmp) / "x.o3lib"
            lib.write_text(LIBERTY)
            self.assertEqual(l2l.main([str(lib), str(out)]), 0)
            import hashlib
            sha = hashlib.sha256(LIBERTY.encode()).hexdigest()
            head = ("# generated by tools/silicon/liberty_to_o3lib.py from x.lib "
                    f"(sha256 {sha}); sky130_fd_sc_hd _1 subset\n")
            self.assertEqual(out.read_text(), head + GOLDEN_LIB)

    def test_function_conversion(self) -> None:
        self.assertEqual(l2l.convert_function("(A1&A2) | !B1"), "( A1 & A2 ) | ~ B1")
        self.assertEqual(l2l.convert_function("A*B+C"), "A & B | C")
        self.assertIsNone(l2l.convert_function("A'"))

    def test_shipped_library(self) -> None:
        text = LIB.read_text()
        self.assertIn("library sky130hd", text)
        self.assertIn("sha256", text.splitlines()[0])
        self.assertEqual(text.count("\ncell "), 84)
        self.assertIn("cell sky130_fd_sc_hd__dfxtp_1 gate", text)
        self.assertNotIn("conb_1", text)


class CleanNetlistTest(unittest.TestCase):
    GV = """(* src = "a.v:1.1-3.9" *)
module m (a, y, z);
  input a;
  output y;
  output z;
  wire \\$n1 ;
  (* src = "a.v:2.1-2.9" *)
  sky130_fd_sc_hd__and2_1 \\$c1 (  // a.v:2
    .A(a),
    .B(1'b1),
    .X(\\$n1 )
  );
  sky130_fd_sc_hd__buf_1 \\$c2 (
    .A(\\$n1 ),
    .X(y)
  );
  assign z = 1'b0;
endmodule
"""

    def test_ties_names_and_rows(self) -> None:
        locs = {"$c1": ("sky130_fd_sc_hd__and2_1", ["/r/a.v:2.1-2.9"]),
                "$c2": ("sky130_fd_sc_hd__buf_1", ["/r/a.v:3.1-3.4"]),
                "$k": ("$_CONST1_", ["/r/a.v:2.5-2.9"])}
        with tempfile.TemporaryDirectory() as tmp:
            gv, clean = Path(tmp) / "g.v", Path(tmp) / "clean.v"
            gv.write_text(self.GV)
            rows = sf.clean_netlist(gv, clean, locs)
            text = clean.read_text()
            self.assertNotIn("(*", text)
            self.assertNotIn("//", text)
            self.assertNotIn("1'b", text)
            self.assertNotIn("assign", text)
            self.assertIn("o3__c1 (", text)
            self.assertEqual(text.count("sky130_fd_sc_hd__conb_1"), 2)
            by = {r["inst"]: r for r in rows}
            self.assertEqual(by["o3__c1"]["odin_name"], "$c1")
            self.assertEqual(by["o3__c1"]["src_chain"], "/r/a.v:2.1-2.9")
            ties = [r for r in rows if r["tie"]]
            self.assertEqual(sorted(r["tie"] for r in ties), ["0", "1"])
            # a constant with an HDL location keeps it; one without has no chain
            self.assertEqual([r["src_chain"] for r in ties if r["tie"] == "1"], ["/r/a.v:2.5-2.9"])
            self.assertEqual([r["src_chain"] for r in ties if r["tie"] == "0"], [""])

    def test_tie_origin_labels(self) -> None:
        rows = [{"inst": "o3_tie_0", "odin_name": "", "master": sf.CONB, "src_chain": "",
                 "tie": "0"},
                {"inst": "o3_tie_1", "odin_name": "", "master": sf.CONB,
                 "src_chain": "a.v:2.5-2.9", "tie": "1"}]
        ir = {"$k": ("$_CONST1_", ["a.v:2.5-2.9"])}
        got = {o["name"]: o for o in sf.gates_objects(rows, ir, Path("."))}
        self.assertEqual(got["o3_tie_0"]["origin"], "physical:tie")
        self.assertEqual(got["o3_tie_0"]["links"], [])
        self.assertEqual(got["o3_tie_1"]["origin"], "hdl")
        self.assertEqual(got["o3_tie_1"]["links"][0]["to"], "ir:$k")
        self.assertEqual(got["o3_tie_1"]["links"][0]["kind"], "cone")


class CensusJoinTest(unittest.TestCase):
    def dump(self, out: Path, name: str, rows: list[tuple[str, str, int, int]]) -> None:
        (out / "or").mkdir(exist_ok=True)
        with (out / "or" / f"{name}.csv").open("w", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(["inst", "master", "x", "y", "orient", "status", "step"])
            for inst, master, x, y in rows:
                w.writerow([inst, master, x, y, "N", "PLACED", name])

    def test_census_classes(self) -> None:
        a, b = "sky130_fd_sc_hd__nand2_1", "sky130_fd_sc_hd__nand2_2"
        t = "sky130_fd_sc_hd__tapvpwrvgnd_1"
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp)
            self.dump(out, "s00_link", [("u1", a, 0, 0), ("u2", a, 0, 0), ("u3", a, 0, 0),
                                        ("u4", a, 0, 0)])
            self.dump(out, "s01_floorplan", [("u1", a, 1, 1), ("u2", b, 0, 0), ("u3a", a, 0, 0),
                                             ("t0", t, 5, 5)])
            rows = sf.census(out)
            second = rows[1]
            self.assertEqual((second["moved"], second["resized"], second["renamed"]),
                             (1, 1, 1))
            self.assertEqual((second["removed"], second["inserted"]), (1, 1))
            self.assertEqual(second["inserted_kinds"], {"tap": 1})

    def test_join_by_type_and_location(self) -> None:
        ext = ("scale 1000 1 500000\n"
               "use sky130_fd_sc_hd__inv_1 sky130_fd_sc_hd__inv_1_0 1 0 100 0 1 200\n"
               "use sky130_fd_sc_hd__inv_1 sky130_fd_sc_hd__inv_1_1 1 0 -300 0 -1 700\n")
        sizes = {"sky130_fd_sc_hd__inv_1": (276, 544)}
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "t.ext"
            path.write_text(ext)
            cells = sf.extracted_cells(path, sizes)
            self.assertEqual([(c["x"], c["y"]) for c in cells], [(500, 1000), (-1500, 780)])
            comps = {("sky130_fd_sc_hd__inv_1", 500, 1000): "u1"}
            self.assertIn((cells[0]["master"], cells[0]["x"], cells[0]["y"]), comps)
            self.assertNotIn((cells[1]["master"], cells[1]["x"], cells[1]["y"]), comps)

    def test_def_components(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "r.def"
            path.write_text(
                "COMPONENTS 2 ;\n"
                "    - u1 sky130_fd_sc_hd__inv_1 + PLACED ( 500 1000 ) N ;\n"
                "    - FILL_0 sky130_fd_sc_hd__fill_1 + SOURCE DIST + PLACED ( 0 0 ) FS ;\n"
                "END COMPONENTS\n")
            self.assertEqual(sf.def_components(path),
                             {("sky130_fd_sc_hd__inv_1", 500, 1000): "u1",
                              ("sky130_fd_sc_hd__fill_1", 0, 0): "FILL_0"})


@unittest.skipUnless(ODIN3, "ODIN3_CLI not set (CTest python_tools)")
class OdinOnlyStepsTest(unittest.TestCase):
    def test_read_elab_map_equiv_netlist(self) -> None:
        design = MICRO / "bm_DL_4_bit_comparator.v"
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp)
            tools = sf.Tools(odin3=Path(ODIN3))
            run = sf.Run(design, "bm_DL_4_bit_comparator", out, LIB, tools, "",
                         sf.ODIN_ONLY, REPO_ROOT)
            self.assertEqual(sf.run(run), 0, run.log)
            self.assertEqual(schema_check.check_dir(out / "prov", SCHEMAS), [])
            index = json.loads((out / "prov" / "index.json").read_text())
            self.assertEqual([s["id"] for s in index["steps"]],
                             ["read", "elab", "map", "equiv", "netlist"])
            gates = (out / "prov" / index["steps"][2]["objects"]).read_text().splitlines()
            rows = [json.loads(x) for x in gates]
            self.assertEqual(len(rows), 17)
            self.assertTrue(all(r["origin"] == "hdl" and r["links"] for r in rows))
            self.assertTrue(all(r["links"][0]["to"].startswith("ir:") for r in rows))
            equiv = json.loads((out / "prov" / index["steps"][3]["file"]).read_text())
            self.assertEqual(equiv["check"]["result"], "equivalent")
            self.assertNotIn("/home/", (out / "prov" / "index.json").read_text())

    def test_missing_tools_are_named(self) -> None:
        t = sf.Tools(odin3=Path("odin3"))
        need = sf.missing(t, sf.TOP_STEPS)
        text = "\n".join(need)
        for word in ("openroad", "magic", "netgen", "klayout", "sky130A"):
            self.assertIn(word, text)
        self.assertEqual(sf.missing(t, sf.ODIN_ONLY), [])


@unittest.skipUnless(ODIN3 and TOOLS, "ODIN3_CLI or ODIN3_SILICON_TOOLS not set")
class FullFlowTest(unittest.TestCase):
    def run_design(self, name: str, clock: str) -> tuple[Path, dict[str, object]]:
        tools = sf.discover(Path(ODIN3), Path(TOOLS), None)
        gone = sf.missing(tools, sf.TOP_STEPS)
        if gone:
            self.skipTest("missing: " + "; ".join(gone))
        tmp = tempfile.mkdtemp()
        out = Path(tmp)
        run = sf.Run(MICRO / f"{name}.v", name, out, LIB, tools, clock, sf.TOP_STEPS, REPO_ROOT)
        self.assertEqual(sf.run(run), 0, run.log)
        return out, json.loads((out / "join.json").read_text())

    def test_comparator(self) -> None:
        out, join = self.run_design("bm_DL_4_bit_comparator", "")
        self.assertEqual(join["join_rate"], 1.0)
        self.assertEqual(join["logic_with_hdl_chain"], 17)
        self.assertEqual(join["names_in_gds"], 0)
        self.assertEqual(join["names_in_extracted_spice"], 0)
        self.assertEqual(schema_check.check_dir(out / "prov", SCHEMAS), [])
        cen = json.loads((out / "census.json").read_text())
        self.assertEqual(cen[-1]["inserted_kinds"], {"fill": 26})
        self.assertEqual(sum(c["renamed"] + c["removed"] for c in cen), 0)

    def test_shift_register_with_clock(self) -> None:
        out, join = self.run_design("bm_DL_4_bit_shift_register", "Clock")
        self.assertEqual(join["join_rate"], 1.0)
        self.assertEqual(join["logic_with_hdl_chain"], 12)
        self.assertEqual(join["logic_cells"], 15)  # + 3 clock-tree buffers
        self.assertEqual(schema_check.check_dir(out / "prov", SCHEMAS), [])
        placed = (out / "prov" / "06-place.objects.jsonl").read_text().splitlines()
        origins = {json.loads(x)["origin"] for x in placed}
        self.assertIn("physical:cts_buffer", origins)
        self.assertIn("hdl", origins)


