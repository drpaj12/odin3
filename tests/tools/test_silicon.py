class RefSpiceTest(unittest.TestCase):
    def test_reason_skips_notices_and_paths(self) -> None:
        text = ("equiv-check: notice: /a/b/rtl.blif: 8 latch(es) treated as 0\n"
                "equiv-check: error: latch $n21 is clocked by internal net, see /a/b/c.blif\n")
        self.assertEqual(sf._reason(text),
                         "equiv-check: error: latch $n21 is clocked by internal net, see <path>")
        self.assertEqual(sf._reason(""), "gates are not equivalent to the RTL")

    def test_open_pin_gets_its_own_net(self) -> None:
        pins = ["VGND", "VNB", "VPB", "VPWR", "HI", "LO"]
        conn = {"VGND": "VSS", "VNB": "VSS", "VPB": "VDD", "VPWR": "VDD", "LO": "zero", "HI": ""}
        line = sf.ref_instance_line("t0", "sky130_fd_sc_hd__conb_1", pins, conn)
        self.assertEqual(line, "Xt0 VSS VSS VDD VDD nc_t0_HI zero sky130_fd_sc_hd__conb_1")
        self.assertEqual(len(line.split()), len(pins) + 2)
        absent = {k: v for k, v in conn.items() if k != "HI"}
        self.assertEqual(sf.ref_instance_line("t0", "sky130_fd_sc_hd__conb_1", pins, absent), line)

    def test_aliased_ports_use_the_layout_port_name(self) -> None:
        """`assign out[6] = out[0];` in final.v: the layout keeps one port name for the net."""
        text = "wire x;\n assign out[12] = out[0];\n assign out[6] = out[0];\n assign w = a[1];\n"
        ports = ["a[1]", "out[6]", "VDD", "VSS"]
        rename, groups = sf.port_aliases(text, ports)
        self.assertEqual(rename, {"out[0]": "out[6]", "out[12]": "out[6]", "w": "a[1]"})
        self.assertEqual(groups, [["out[0]", "out[12]", "out[6]"], ["a[1]", "w"]])
        self.assertEqual(sf.port_aliases("wire x;\n", ports), ({}, []))

    def test_alias_group_without_layout_port_is_left_alone(self) -> None:
        rename, _groups = sf.port_aliases("assign p = q;\n", ["z"])
        self.assertEqual(rename, {})


class EquivVerdictTest(unittest.TestCase):
    """An equivalence the tool cannot decide is a WARNING and `not proven`, not a stop."""

    @staticmethod
    def fake(*replies: tuple[int, str]) -> tuple[list[list[str]], object]:
        calls: list[list[str]] = []
        queue = list(replies)

        def run(argv: object) -> subprocess.CompletedProcess[str]:
            calls.append([str(a) for a in argv])  # type: ignore[attr-defined]
            code, text = queue.pop(0)
            return subprocess.CompletedProcess([], code, text, "")

        return calls, run

    def test_equivalent(self) -> None:
        calls, run = self.fake((0, "equiv-check: equivalent (abc dsec)\n"))
        check, warn, _text = sf.equiv_verdict(Path("c.py"), Path("a"), Path("b"), run)  # type: ignore[arg-type]
        self.assertEqual(check["result"], "equivalent")
        self.assertIsNone(warn)
        self.assertEqual(len(calls), 1)

    def test_undriven_output_is_tied_to_zero_and_not_proven(self) -> None:
        msg = ("equiv-check: /a/b.blif: undriven net raddr_o[0] reaches primary output "
               "raddr_o[0]; pass --allow-undriven to tie it to 0\n")
        calls, run = self.fake((2, msg), (0, "equiv-check: equivalent (abc dsec)\n"))
        check, warn, _text = sf.equiv_verdict(Path("c.py"), Path("a"), Path("b"), run)  # type: ignore[arg-type]
        self.assertIn("--allow-undriven", calls[1])
        self.assertEqual(check["result"], "not-proven")
        self.assertTrue(check["detail"].startswith("equiv: not proven: "))
        self.assertIn("undriven net raddr_o[0]", check["detail"])
        self.assertIn("tied to 0", check["detail"])
        self.assertNotIn("/a/b.blif", check["detail"])
        self.assertIsNotNone(warn)
        self.assertTrue(str(warn).startswith("WARNING equiv: not proven"))

    def test_tool_limit_is_not_proven(self) -> None:
        _calls, run = self.fake((2, "equiv-check: /t/x.blif:3: unsupported: latch q is clocked\n"))
        check, warn, _text = sf.equiv_verdict(Path("c.py"), Path("a"), Path("b"), run)  # type: ignore[arg-type]
        self.assertEqual(check["result"], "not-proven")
        self.assertIn("equiv: not proven: equiv-check: <path>:3: unsupported", check["detail"])
        self.assertIsNotNone(warn)

    def test_a_proven_difference_still_fails(self) -> None:
        _calls, run = self.fake((1, "equiv-check: NOT equivalent\n"))
        check, warn, _text = sf.equiv_verdict(Path("c.py"), Path("a"), Path("b"), run)  # type: ignore[arg-type]
        self.assertEqual(check["result"], "not-equivalent")
        self.assertIsNone(warn)


class CensusJoinTest(unittest.TestCase):
    def dump(self, out: Path, name: str, rows: list[tuple[str, str, int, int]]) -> None:
        (out / "or").mkdir(exist_ok=True)
        with (out / "or" / f"{name}.csv").open("w", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(["inst", "master", "x", "y", "orient", "status", "step"])
            for inst, master, x, y in rows:
                w.writerow([inst, master, x, y, "N", "PLACED", name])

    def test_census_classes(self) -> None:
        a, b = "sky130_fd_sc_hd__nand2_1", "sky130_fd_sc_hd__nand2_2"
        t = "sky130_fd_sc_hd__tapvpwrvgnd_1"
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp)
            self.dump(out, "s00_link", [("u1", a, 0, 0), ("u2", a, 0, 0), ("u3", a, 0, 0),
                                        ("u4", a, 0, 0)])
            self.dump(out, "s01_floorplan", [("u1", a, 1, 1), ("u2", b, 0, 0), ("u3a", a, 0, 0),
                                             ("t0", t, 5, 5)])
            rows = sf.census(out)
            second = rows[1]
            self.assertEqual((second["moved"], second["resized"], second["renamed"]),
                             (1, 1, 1))
            self.assertEqual((second["removed"], second["inserted"]), (1, 1))
            self.assertEqual(second["inserted_kinds"], {"tap": 1})

    def test_join_by_type_and_location(self) -> None:
        ext = ("scale 1000 1 500000\n"
               "use sky130_fd_sc_hd__inv_1 sky130_fd_sc_hd__inv_1_0 1 0 100 0 1 200\n"
               "use sky130_fd_sc_hd__inv_1 sky130_fd_sc_hd__inv_1_1 1 0 -300 0 -1 700\n")
        sizes = {"sky130_fd_sc_hd__inv_1": (276, 544)}
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "t.ext"
            path.write_text(ext)
            cells = sf.extracted_cells(path, sizes)
            self.assertEqual([(c["x"], c["y"]) for c in cells], [(500, 1000), (-1500, 780)])
            comps = {("sky130_fd_sc_hd__inv_1", 500, 1000): "u1"}
            self.assertIn((cells[0]["master"], cells[0]["x"], cells[0]["y"]), comps)
            self.assertNotIn((cells[1]["master"], cells[1]["x"], cells[1]["y"]), comps)

    def test_def_components(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "r.def"
            path.write_text(
                "COMPONENTS 2 ;\n"
                "    - u1 sky130_fd_sc_hd__inv_1 + PLACED ( 500 1000 ) N ;\n"
                "    - FILL_0 sky130_fd_sc_hd__fill_1 + SOURCE DIST + PLACED ( 0 0 ) FS ;\n"
                "END COMPONENTS\n")
            self.assertEqual(sf.def_components(path),
                             {("sky130_fd_sc_hd__inv_1", 500, 1000): "u1",
                              ("sky130_fd_sc_hd__fill_1", 0, 0): "FILL_0"})


