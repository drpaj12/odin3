class LibertyTest(unittest.TestCase):
    def test_golden_text(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            lib, out = Path(tmp) / "x.lib", Path(tmp) / "x.o3lib"
            lib.write_text(LIBERTY)
            self.assertEqual(l2l.main([str(lib), str(out)]), 0)
            import hashlib
            sha = hashlib.sha256(LIBERTY.encode()).hexdigest()
            head = ("# generated by tools/silicon/liberty_to_o3lib.py from x.lib "
                    f"(sha256 {sha}); sky130_fd_sc_hd _1 subset\n")
            self.assertEqual(out.read_text(), head + GOLDEN_LIB)

    def test_function_conversion(self) -> None:
        self.assertEqual(l2l.convert_function("(A1&A2) | !B1"), "( A1 & A2 ) | ~ B1")
        self.assertEqual(l2l.convert_function("A*B+C"), "A & B | C")
        self.assertIsNone(l2l.convert_function("A'"))

    def test_shipped_library(self) -> None:
        text = LIB.read_text()
        self.assertIn("library sky130hd", text)
        self.assertIn("sha256", text.splitlines()[0])
        self.assertEqual(text.count("\ncell "), 84)
        self.assertIn("cell sky130_fd_sc_hd__dfxtp_1 gate", text)
        self.assertNotIn("conb_1", text)


class CleanNetlistTest(unittest.TestCase):
    GV = """(* src = "a.v:1.1-3.9" *)
module m (a, y, z);
  input a;
  output y;
  output z;
  wire \\$n1 ;
  (* src = "a.v:2.1-2.9" *)
  sky130_fd_sc_hd__and2_1 \\$c1 (  // a.v:2
    .A(a),
    .B(1'b1),
    .X(\\$n1 )
  );
  sky130_fd_sc_hd__buf_1 \\$c2 (
    .A(\\$n1 ),
    .X(y)
  );
  assign z = 1'b0;
endmodule
"""

    def test_ties_names_and_rows(self) -> None:
        locs = {"$c1": ("sky130_fd_sc_hd__and2_1", ["/r/a.v:2.1-2.9"]),
                "$c2": ("sky130_fd_sc_hd__buf_1", ["/r/a.v:3.1-3.4"]),
                "$k": ("$_CONST1_", ["/r/a.v:2.5-2.9"])}
        with tempfile.TemporaryDirectory() as tmp:
            gv, clean = Path(tmp) / "g.v", Path(tmp) / "clean.v"
            gv.write_text(self.GV)
            rows = sf.clean_netlist(gv, clean, locs)
            text = clean.read_text()
            self.assertNotIn("(*", text)
            self.assertNotIn("//", text)
            self.assertNotIn("1'b", text)
            self.assertNotIn("assign", text)
            self.assertIn("o3__c1 (", text)
            self.assertEqual(text.count("sky130_fd_sc_hd__conb_1"), 2)
            by = {r["inst"]: r for r in rows}
            self.assertEqual(by["o3__c1"]["odin_name"], "$c1")
            self.assertEqual(by["o3__c1"]["src_chain"], "/r/a.v:2.1-2.9")
            ties = [r for r in rows if r["tie"]]
            self.assertEqual(sorted(r["tie"] for r in ties), ["0", "1"])
            # a constant with an HDL location keeps it; one without has no chain
            self.assertEqual([r["src_chain"] for r in ties if r["tie"] == "1"], ["/r/a.v:2.5-2.9"])
            self.assertEqual([r["src_chain"] for r in ties if r["tie"] == "0"], [""])

    def test_tie_origin_labels(self) -> None:
        rows = [{"inst": "o3_tie_0", "odin_name": "", "master": sf.CONB, "src_chain": "",
                 "tie": "0"},
                {"inst": "o3_tie_1", "odin_name": "", "master": sf.CONB,
                 "src_chain": "a.v:2.5-2.9", "tie": "1"}]
        ir = {"$k": ("$_CONST1_", ["a.v:2.5-2.9"])}
        got = {o["name"]: o for o in sf.gates_objects(rows, ir, Path("."))}
        self.assertEqual(got["o3_tie_0"]["origin"], "physical:tie")
        self.assertEqual(got["o3_tie_0"]["links"], [])
        self.assertEqual(got["o3_tie_1"]["origin"], "hdl")
        self.assertEqual(got["o3_tie_1"]["links"][0]["to"], "hdl:a.v:2.5-2.9")
        self.assertEqual(got["o3_tie_1"]["links"][0]["kind"], "cone")

    def test_gate_links_are_linear_in_cells(self) -> None:
        """Many IR cells share a span: one link per span of the gate chain, not per IR cell."""
        ir = {f"$c{i}": ("$_AND_", ["a.v:1.1-9.9"]) for i in range(2000)}
        ir["$one"] = ("$_NOT_", ["a.v:3.1-3.4"])
        rows = [{"inst": f"g{i}", "odin_name": "", "master": "m",
                 "src_chain": "a.v:1.1-9.9|a.v:3.1-3.4|a.v:7.1-7.2", "tie": ""} for i in range(50)]
        got = sf.gates_objects(rows, ir, Path("."))
        self.assertEqual(sum(len(o["links"]) for o in got), 50 * 2)  # a.v:7.1-7.2 is not in the IR
        self.assertEqual([lk["to"] for lk in got[0]["links"]],
                         ["hdl:a.v:1.1-9.9", "hdl:a.v:3.1-3.4"])


