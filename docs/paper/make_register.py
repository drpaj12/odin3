#!/usr/bin/env python3
"""Write register.tex (the appendix research-log tables) from hypotheses.md.

Usage (from docs/paper): python3 make_register.py

One row per hypothesis (grouped H-IDs count once), including DISMISSED and INCONCLUSIVE ones and the
untested ones; the framing column of hypotheses.md is not printed. Standard library only.
"""

from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
CHUNK = 12
SPECIAL = str.maketrans({"&": r"\&", "%": r"\%", "#": r"\#", "$": r"\$", "{": r"\{", "}": r"\}",
                         "^": r"\^{}", "~": r"\~{}"})


def esc(text: str) -> str:
    """LaTeX-escape one markdown cell (backticks become \\code)."""
    parts = text.split("`")
    out = []
    for i, part in enumerate(parts):
        if i % 2:
            out.append(r"\code{" + part.translate(SPECIAL).replace("_", r"\_") + "}")
            continue
        t = part.translate(SPECIAL).replace("_", r"\_")
        t = t.replace(">=", r"$\ge$").replace("<=", r"$\le$")
        t = re.sub(r"(?<=\s)<(?=\s)", r"$<$", t)
        t = re.sub(r"(?<=\s)>(?=\s)", r"$>$", t)
        out.append(t)
    return "".join(out)


def verdict_word(cell: str) -> str:
    """Normalise the verdict cell to one of the paper's verdict words."""
    for word in ("POSSIBLY GOOD", "USEFUL", "DISMISSED", "INCONCLUSIVE", "MEASUREMENT"):
        if cell.startswith(word):
            return word
    raise SystemExit(f"unknown verdict: {cell}")


def rows() -> list[tuple[str, str, str, str, str]]:
    """(id, round, hypothesis, result, verdict) for every register row."""
    out = []
    untested = False
    for raw in (HERE / "hypotheses.md").read_text(encoding="utf-8").splitlines():
        if raw.startswith("## "):
            untested = raw.startswith("## Untested")
            continue
        if not raw.startswith("| ") or raw.startswith("| ---") or raw.startswith("| H-ID"):
            continue
        c = [x.strip() for x in raw.strip().strip("|").split("|")]
        if untested and len(c) == 3:
            out.append((c[0], "-", c[1], "not run; needs: " + c[2], "UNTESTED"))
        elif len(c) == 11:
            found = re.match(r"[A-Za-z]+\d*[a-z]?", c[1])
            rnd = found.group(0) if found else c[1]
            out.append((c[0], rnd, c[3], c[7], verdict_word(c[9])))
    return out


def main() -> None:
    """Write register.tex."""
    data = rows()
    lines = ["% Generated by make_register.py from hypotheses.md; do not edit by hand.\n"]
    for n in range(0, len(data), CHUNK):
        part = data[n:n + CHUNK]
        first, last = n + 1, n + len(part)
        lines += [
            "\\begin{table*}[t]\n",
            f"\\caption{{Research log, hypotheses {first} to {last} of {len(data)}: "
            "every hypothesis, one row each, with the verdict.}\n",
            f"\\label{{tab:register-{n // CHUNK + 1}}}\n",
            "\\centering\\scriptsize\n",
            "\\begin{tabular}{@{}p{0.9cm}p{0.7cm}p{5.2cm}p{8.0cm}p{1.9cm}@{}}\n",
            "\\toprule\nID & Round & Hypothesis & Result & Verdict \\\\\n\\midrule\n",
        ]
        for hid, rnd, hyp, res, ver in part:
            cells = f"{esc(hid)} & {esc(rnd)} & {esc(hyp)} & {esc(res)}"
            lines.append(f"{cells} & \\textsc{{{ver.lower()}}} \\\\\n")
        lines += ["\\bottomrule\n\\end{tabular}\n\\end{table*}\n\n"]
    (HERE / "register.tex").write_text("".join(lines), encoding="utf-8", newline="\n")
    print(len(data), "rows")


if __name__ == "__main__":
    main()
